#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn has_about_a_hundred_and_fifty_unique_lowercase_entries() {
        let set: HashSet<&str> = ENGLISH_STOP_WORDS.iter().copied().collect();
        assert_eq!(set.len(), ENGLISH_STOP_WORDS.len(), "no duplicates");
        assert!(ENGLISH_STOP_WORDS.len() >= 140 && ENGLISH_STOP_WORDS.len() <= 220);
        assert!(ENGLISH_STOP_WORDS.iter().all(|w| *w == w.to_lowercase()));
        assert!(ENGLISH_STOP_WORDS.is_sorted());
    }
}
